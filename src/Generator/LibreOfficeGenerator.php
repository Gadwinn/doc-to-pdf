<?php

declare(strict_types=1);

namespace G\DocToPdf\Generator;

use G\DocToPdf\Exception\DocToPdfException;

/**
 * LibreOffice headless PDF generator.
 *
 * Converts ODT/ODS documents to PDF using LibreOffice in headless mode.
 * Provides the best fidelity for OpenDocument formats but requires
 * LibreOffice to be installed on the system.
 *
 * Priority: 100 (highest - best fidelity)
 *
 * @package G\DocToPdf\Generator
 */
class LibreOfficeGenerator implements GeneratorInterface
{
    private const PRIORITY = 100;
    private const TEMP_NAME_BYTES = 8;
    private const DEFAULT_PATHS = [
        '/usr/bin/soffice',
        '/usr/local/bin/soffice',
        'C:\\Program Files\\LibreOffice\\program\\soffice.exe',
        'C:\\Program Files (x86)\\LibreOffice\\program\\soffice.exe',
    ];

    private ?string $binaryPath = null;

    /**
     * Constructor.
     *
     * @param string|null $customPath Custom path to LibreOffice binary
     */
    public function __construct(?string $customPath = null)
    {
        if ($customPath !== null) {
            $this->binaryPath = $customPath;
        }
    }

    /**
     * Check if LibreOffice is available on the system.
     *
     * @return bool True if LibreOffice binary is found, false otherwise
     */
    public function supports(): bool
    {
        return $this->findBinary() !== null;
    }

    /**
     * Get generator priority.
     *
     * @return int Priority value (100 = highest/best fidelity)
     */
    public function getPriority(): int
    {
        return self::PRIORITY;
    }

    /**
     * Generate PDF from ODT/ODS file using LibreOffice.
     *
     * @param string $content File path to ODT/ODS document
     * @param array<string, mixed> $options Generation options
     * @return string PDF binary content
     * @throws DocToPdfException If LibreOffice is not available or conversion fails
     */
    public function generate(string $content, array $options = []): string
    {
        $binary = $this->findBinary();
        if ($binary === null) {
            throw new DocToPdfException('LibreOffice is not available on this system');
        }

        if (!file_exists($content)) {
            throw new DocToPdfException("Source file not found: {$content}");
        }

        // Create temp directory for conversion
        $tempDir = sys_get_temp_dir() . '/doctopdf_lo_' . bin2hex(random_bytes(self::TEMP_NAME_BYTES));
        if (!mkdir($tempDir, 0o700, true)) {
            throw new DocToPdfException("Failed to create temporary directory: {$tempDir}");
        }

        try {
            // Build LibreOffice command
            $command = sprintf(
                '%s --headless --convert-to pdf --outdir %s %s 2>&1',
                escapeshellarg($binary),
                escapeshellarg($tempDir),
                escapeshellarg($content)
            );

            // Execute conversion
            exec($command, $output, $exitCode);

            if ($exitCode !== 0) {
                throw new DocToPdfException(
                    'LibreOffice conversion failed: ' . implode("\n", $output)
                );
            }

            // Find generated PDF file
            $pdfFile = $this->findGeneratedPdf($tempDir, $content);
            if ($pdfFile === null) {
                throw new DocToPdfException('PDF file was not generated by LibreOffice');
            }

            // Read PDF content
            $pdfContent = file_get_contents($pdfFile);
            if ($pdfContent === false) {
                throw new DocToPdfException("Failed to read generated PDF: {$pdfFile}");
            }

            return $pdfContent;
        } finally {
            // Clean up temporary files
            $this->cleanupTempDir($tempDir);
        }
    }

    /**
     * Find LibreOffice binary.
     *
     * @return string|null Path to binary or null if not found
     */
    private function findBinary(): ?string
    {
        // Check custom path first
        if ($this->binaryPath !== null && file_exists($this->binaryPath)) {
            return $this->binaryPath;
        }

        // Check default paths
        foreach (self::DEFAULT_PATHS as $path) {
            if (file_exists($path)) {
                $this->binaryPath = $path;
                return $path;
            }
        }

        // Try to find in PATH
        $command = PHP_OS_FAMILY === 'Windows' ? 'where soffice 2>NUL' : 'command -v soffice 2>/dev/null';
        $result = @shell_exec($command);
        if (is_string($result)) {
            // "where" may list several matches, one per line: keep the first
            $first = trim(strtok($result, "\r\n") ?: '');
            if ($first !== '' && file_exists($first)) {
                $this->binaryPath = $first;
                return $this->binaryPath;
            }
        }

        return null;
    }

    /**
     * Find the generated PDF file in the temp directory.
     *
     * @param string $tempDir Temporary directory path
     * @param string $sourceFile Original source file path
     * @return string|null Path to generated PDF or null if not found
     */
    private function findGeneratedPdf(string $tempDir, string $sourceFile): ?string
    {
        $baseName = pathinfo($sourceFile, PATHINFO_FILENAME);
        $pdfFile = $tempDir . DIRECTORY_SEPARATOR . $baseName . '.pdf';

        if (file_exists($pdfFile)) {
            return $pdfFile;
        }

        // Fallback: search for any PDF file in temp dir
        $files = glob($tempDir . DIRECTORY_SEPARATOR . '*.pdf');
        return $files[0] ?? null;
    }

    /**
     * Clean up temporary directory and its contents.
     *
     * @param string $tempDir Directory to clean up
     */
    private function cleanupTempDir(string $tempDir): void
    {
        if (!is_dir($tempDir)) {
            return;
        }

        $files = glob($tempDir . DIRECTORY_SEPARATOR . '*');
        if ($files !== false) {
            foreach ($files as $file) {
                if (is_file($file)) {
                    @unlink($file);
                }
            }
        }

        @rmdir($tempDir);
    }
}
